// Prose guards ported from qua-cli internal/skill/skill_test.go (ADR 0010, 0054).
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

const dir = new URL('../plugins/qua/skills/', import.meta.url).pathname
const skills = Object.fromEntries(readdirSync(dir).map((d) => [d, readFileSync(join(dir, d, 'SKILL.md'), 'utf8')]))
const commands = Object.keys(skills).filter((n) => n !== 'qua')

const has = (label, body, words) => {
  const missing = words.filter((w) => !body.includes(w))
  assert.deepEqual(missing, [], `${label} missing`)
}

function frontmatter(body) {
  const m = body.match(/^---\n([\s\S]*?)\n---\n/)
  if (!m) return null
  return Object.fromEntries(m[1].split('\n').map((l) => l.match(/^([a-z-]+): (.+)$/)?.slice(1) ?? [l, '']))
}

test('all eight command skills ship', () => {
  assert.deepEqual(commands.sort(), ['qua-automate', 'qua-bug-report', 'qua-explore', 'qua-init', 'qua-record', 'qua-regress', 'qua-test-case', 'qua-validate'])
})

test('qua skill is static', () => {
  const body = skills.qua
  has('qua', body, [
    'Qua MCP is not connected', 'Do not fall back to the `qua` CLI', '`agent:` line of `qua_project_get`',
    'did **not** perform the step', 'Do not close and reopen the session', 'qua_project_get', 'qua_project_set',
    'explicitly asks for one', 'Never ask for or store secrets', '/qua-init',
  ])
  for (const w of ['generated by qua init', '.mcp.json', '| browser |', 'checked_at', 'agent: "', '{{'])
    assert.ok(!body.includes(w), `must not contain ${w}`)
  assert.doesNotMatch(body, /\d+\.\d+\.\d+/, 'skill must not name versions')
  for (const line of body.split('\n')) assert.ok(line.length <= 400, `line too long: ${line.slice(0, 60)}`)
  const forbidden = ['browser_navigate', 'browser_tabs', 'browser_click', 'browser_type', 'browser_fill', 'browser_snapshot', 'browser_take_screenshot']
  has('qua forbidden Cursor tools', body, forbidden.map((t) => '`' + t + '`'))
  has('qua bridge guidance', body, ['Cursor only (`agent: cursor`)', '`qua patch`'])
})

test('frontmatter, title and project rules in every skill', () => {
  for (const [name, body] of Object.entries(skills)) {
    const fm = frontmatter(body)
    assert.ok(fm && fm.name === name && fm.description, `${name}: bad frontmatter`)
    assert.ok(body.startsWith(`---\nname: ${name}\ndescription: `), `${name}: frontmatter order`)
    if (name === 'qua') continue
    assert.ok(!body.replaceAll('TODO(qua)', '').includes('TODO') && body.includes('# /' + name), `${name}: placeholder or missing title`)
    if (name !== 'qua-init') assert.ok(body.includes('qua_project_get()'), `${name}: must start with qua_project_get`)
    assert.ok(body.includes('Never edit `.qua/project.yaml`') || body.includes('by hand'), `${name}: missing project.yaml rule`)
  }
})

